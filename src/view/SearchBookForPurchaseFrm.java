    @Override
    public void actionPerformed(ActionEvent e) {
        if (e.getSource() == btnSearch) {
            BookDAO bookDAO = new BookDAO();
            Book[] books = bookDAO.searchBook(txtKeyword.getText().trim());

            booksFound.clear();
            DefaultTableModel model = (DefaultTableModel) tblBook.getModel();
            model.setRowCount(0);
            for (Book b : books) {
                booksFound.add(b);
                model.addRow(new Object[]{b.getBookID(), b.getISBN(), b.getTitle(), b.getPrice(), b.getDescription()});
            }
        }
    }
