    @Override
    public void actionPerformed(ActionEvent e) {
        if (e.getSource() == btnConfirm) {
            String shippingAddress = txtShippingAddress.getText().trim();
            if (shippingAddress.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Vui lòng nhập địa chỉ giao hàng!");
                return;
            }

            order.setShippingAddress(shippingAddress);
            order.setPaymentMethod((String) cboPaymentMethod.getSelectedItem());

            OrderDAO orderDAO = new OrderDAO();
            if (orderDAO.addOrder(order)) {
                (new PaymentFrm(order)).setVisible(true);
                this.dispose();
            } else {
                JOptionPane.showMessageDialog(this, "Đặt hàng thất bại! Vui lòng thử lại.");
            }
        } else if (e.getSource() == btnBack) {
            ShoppingCartDAO shoppingCartDAO = new ShoppingCartDAO();
            ShoppingCart cart = shoppingCartDAO.getOrCreateCart(order.getCustomer());
            (new ShoppingCartFrm(cart)).setVisible(true);
            this.dispose();
        }
    }
