    /**
     * Mở hộp thoại đăng nhập (có thể chuyển qua lại với hộp thoại Đăng ký).
     * Trả về Account đã đăng nhập thành công, hoặc null nếu người dùng đóng.
     */
    public static Account show(java.awt.Frame parent, boolean startWithRegister) {
        String prefillUsername = null;
        boolean register = startWithRegister;
        while (true) {
            if (register) {
                RegisterDialog r = new RegisterDialog(parent);
                r.setVisible(true);
                if (r.getRegisteredUsername() == null && !r.isGoLogin()) {
                    return null;
                }
                prefillUsername = r.getRegisteredUsername();
            }
            LoginDialog d = new LoginDialog(parent, true);
            if (prefillUsername != null) {
                d.txtUsername.setText(prefillUsername);
            }
            d.setVisible(true);
            if (d.loggedIn != null) {
                return d.loggedIn;
            }
            if (!d.goRegister) {
                return null;
            }
            register = true;
        }
    }

