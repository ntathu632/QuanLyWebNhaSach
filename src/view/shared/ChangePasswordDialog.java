    public static void show(Component parent, String username) {
        if (username == null) {
            JOptionPane.showMessageDialog(parent, "Không xác định được tài khoản đang đăng nhập!");
            return;
        }
        Window owner = parent instanceof Window w ? w : (parent == null ? null : SwingUtilities.getWindowAncestor(parent));
        new ChangePasswordDialog(owner, username).setVisible(true);
    }

