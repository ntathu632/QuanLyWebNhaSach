    /** Thay nội dung trang hiện tại bằng "page", tô sáng đúng mục sidebar — không mở cửa sổ mới. */
    public void navigateTo(InventoryPage page) {
        pnlContent.removeAll();
        pnlContent.add(page.content(this), BorderLayout.CENTER);
        pnlContent.revalidate();
        pnlContent.repaint();

        setActiveNav(page.navKey());
        setTitle("Vintage Books - " + page.title());
    }

    /** Mở trang ứng với mục sidebar "key" (lowstock, import, return, checking, history, books). */
    void go(String key) {
        switch (key) {
            case "lowstock" -> navigateTo(new LowStockFrm(employee));
            case "import" -> navigateTo(new ImportBooksFrm(employee));
            case "return" -> navigateTo(new ReturnToSupplierFrm(employee));
            case "checking" -> navigateTo(new InventoryCheckingFrm(employee));
            case "history" -> navigateTo(new StockHistoryFrm(employee));
            case "books" -> navigateTo(new InventorySearchBookFrm(employee));
            default -> throw new IllegalArgumentException("Mục sidebar không tồn tại: " + key);
        }
    }

    /**
     * Hiệu ứng hover/bo góc của sidebar (FlatLaf style, không đặt được trong
     * Design): nút của trang đang mở chữ + icon sáng, các nút còn lại mờ.
     */
    private void setActiveNav(String key) {
        for (int i = 0; i < navButtons.length; i++) {
            boolean active = navKeys[i].equals(key);
            navButtons[i].setIcon(new FlatIcon(navKinds[i], active ? Color.WHITE : AppTheme.SIDEBAR_TEXT_MUTED, 16));
            if (active) {
                AppTheme.sidebarNav(navButtons[i]);
            } else {
                AppTheme.sidebarNavMuted(navButtons[i]);
            }
        }
        AppTheme.sidebarNavMuted(btnChangePassword);
        AppTheme.sidebarNavMuted(btnLogout);
    }

    /** Dòng chào ở topbar. */
    private static String greeting(Employee employee) {
        String name = (employee != null && employee.getFullName() != null) ? employee.getFullName() : "nhân viên kho";
        return "Xin chào, " + name;
    }

