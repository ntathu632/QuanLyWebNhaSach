    /** Kết quả người dùng nhập khi bấm OK. */
    static final class Result {

        final int quantity;
        final Supplier supplier;
        final String note;

        Result(int quantity, Supplier supplier, String note) {
            this.quantity = quantity;
            this.supplier = supplier;
            this.note = note;
        }
    }

    private Result result;

    /** Hộp thoại "Nhập kho". Trả về null nếu người dùng bấm Cancel / đóng hộp thoại. */
    static Result askImport(Component parent, String bookTitle, Supplier[] suppliers) {
        return ask(parent, "Nhập kho \"" + bookTitle + "\"", null, null, null, suppliers);
    }

    /** Hộp thoại "Xuất trả" (hiện kèm số tồn kho còn lại). Trả về null nếu người dùng bấm Cancel. */
    static Result askReturn(Component parent, String bookTitle, int stock, Supplier[] suppliers) {
        return ask(parent, "Xuất trả \"" + bookTitle + "\"", "Số lượng trả (còn " + stock + "): *",
                "Trả cho nhà cung cấp: *", "Lý do / ghi chú:", suppliers);
    }

    /** Nhãn null = giữ chữ mặc định thiết kế trong Design (chế độ Nhập kho). */
    private static Result ask(Component parent, String title, String quantityLabel, String supplierLabel,
            String noteLabel, Supplier[] suppliers) {
        StockTransactionDialog d = new StockTransactionDialog(AppTheme.windowOf(parent), suppliers);
        d.setTitle(title);
        if (quantityLabel != null) {
            d.lblQuantity.setText(quantityLabel);
            d.lblSupplier.setText(supplierLabel);
            d.lblNote.setText(noteLabel);
        }
        d.pack();
        d.setLocationRelativeTo(d.getOwner());
        d.setVisible(true);
        return d.result;
    }

