    private void btnImportActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnImportActionPerformed
        int row = tblBooks.getSelectedRow();
        if (row < 0 || row >= currentBooks.size()) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn 1 sách để nhập kho!");
            return;
        }
        Book selected = currentBooks.get(row);

        Supplier[] suppliers = new SupplierDAO().searchSupplier("");
        if (suppliers.length == 0) {
            JOptionPane.showMessageDialog(this, "Chưa có nhà cung cấp nào! Vui lòng nhờ Admin thêm nhà cung cấp trước.");
            return;
        }

        StockTransactionDialog.Result input = StockTransactionDialog.askImport(this, selected.getTitle(), suppliers);
        if (input == null) {
            return;
        }
        int quantity = input.quantity;
        Supplier supplier = input.supplier;
        String note = input.note;
        String error = new StockTransactionDAO().recordImport(selected.getBookID(), supplier.getSupplierID(),
                employee.getEmployeeID(), quantity, note);
        if (error == null) {
            JOptionPane.showMessageDialog(this, "Đã nhập " + quantity + " quyển \"" + selected.getTitle()
                    + "\" từ " + supplier.getSupplierName() + "!");
            doSearch();
        } else {
            JOptionPane.showMessageDialog(this, error);
        }
    }//GEN-LAST:event_btnImportActionPerformed

    private void doSearch() {
        InventoryDAO inventoryDAO = new InventoryDAO();
        Book[] found = new BookDAO().searchBook(txtKeyword.getText().trim());
        currentBooks.clear();
        DefaultTableModel model = (DefaultTableModel) tblBooks.getModel();
        model.setRowCount(0);
        for (Book b : found) {
            currentBooks.add(b);
            int stock = inventoryDAO.getInventoryForBook(b.getBookID()).getStockQuantity();
            model.addRow(new Object[]{b.getBookID(), b.getISBN(), b.getTitle(), stock});
        }
    }

