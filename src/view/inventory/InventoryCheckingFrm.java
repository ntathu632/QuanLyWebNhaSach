    private void btnCheckActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCheckActionPerformed
        int row = tblInventory.getSelectedRow();
        if (row < 0 || row >= currentItems.size()) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn 1 sách để kiểm kê!");
            return;
        }
        Inventory selected = currentItems.get(row);
        Integer input = QuantityDialog.ask(this, "Kiểm kê",
                "Số lượng đếm được thực tế cho \"" + selected.getBookTitle() + "\" "
                + "(hệ thống đang ghi " + selected.getStockQuantity() + "):",
                String.valueOf(selected.getStockQuantity()), 0);
        if (input == null) {
            return;
        }
        int actual = input;

        if (actual == selected.getStockQuantity()) {
            JOptionPane.showMessageDialog(this, "Khớp với hệ thống, không cần điều chỉnh.");
            return;
        }

        int diff = actual - selected.getStockQuantity();
        if (new InventoryDAO().adjustStock(selected.getBookID(), actual)) {
            JOptionPane.showMessageDialog(this,
                    "Đã điều chỉnh tồn kho \"" + selected.getBookTitle() + "\" từ " + selected.getStockQuantity()
                    + " thành " + actual + " (" + (diff > 0 ? "+" : "") + diff + ").");
            reload();
        } else {
            JOptionPane.showMessageDialog(this, "Điều chỉnh tồn kho thất bại! Vui lòng thử lại.");
        }
    }//GEN-LAST:event_btnCheckActionPerformed

    private void reload() {
        List<Inventory> rows = new InventoryDAO().allInventory();
        currentItems.clear();
        currentItems.addAll(rows);
        DefaultTableModel model = (DefaultTableModel) tblInventory.getModel();
        model.setRowCount(0);
        for (Inventory inv : rows) {
            model.addRow(new Object[]{inv.getBookTitle(), inv.getStockQuantity()});
        }
    }

