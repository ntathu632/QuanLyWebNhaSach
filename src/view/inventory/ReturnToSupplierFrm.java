    private void btnReturnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnReturnActionPerformed
        int row = tblBooks.getSelectedRow();
        if (row < 0 || row >= currentBooks.size()) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn 1 sách để xuất trả!");
            return;
        }
        Book selected = currentBooks.get(row);
        int stock = new InventoryDAO().getInventoryForBook(selected.getBookID()).getStockQuantity();

        Supplier[] suppliers = new SupplierDAO().searchSupplier("");
        if (suppliers.length == 0) {
            JOptionPane.showMessageDialog(this, "Chưa có nhà cung cấp nào! Vui lòng nhờ quản trị viên thêm nhà cung cấp trước.");
            return;
        }

        StockTransactionDialog.Result input = StockTransactionDialog.askReturn(this, selected.getTitle(), stock, suppliers);
        if (input == null) {
            return;
        }
        int quantity = input.quantity;
        Supplier supplier = input.supplier;
        String note = input.note;
        String error = new StockTransactionDAO().recordReturn(selected.getBookID(), supplier.getSupplierID(),
                employee.getEmployeeID(), quantity, note);
        if (error == null) {
            JOptionPane.showMessageDialog(this, "Đã xuất trả " + quantity + " quyển \"" + selected.getTitle()
                    + "\" cho " + supplier.getSupplierName() + "!");
            doSearch();
        } else {
            JOptionPane.showMessageDialog(this, error);
        }
    }//GEN-LAST:event_btnReturnActionPerformed

