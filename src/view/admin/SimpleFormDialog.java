    /**
     * Hiện hộp thoại OK/Cancel với các trường theo "labels" (điền sẵn theo
     * "initialValues" nếu có, hoặc rỗng nếu null). Trả về mảng giá trị đã
     * nhập theo đúng thứ tự "labels" nếu bấm OK, hoặc null nếu Cancel.
     */
    static String[] show(Component parent, String title, String[] labels, String[] initialValues) {
        if (labels.length > MAX_ROWS) {
            throw new IllegalArgumentException("SimpleFormDialog hỗ trợ tối đa " + MAX_ROWS + " trường");
        }
        SimpleFormDialog panel = new SimpleFormDialog();
        JTextField[] fields = new JTextField[labels.length];

        for (int i = 0; i < MAX_ROWS; i++) {
            boolean used = i < labels.length;
            panel.rowLabels[i].setVisible(used);
            panel.rowFields[i].setVisible(used);
            if (used) {
                panel.rowLabels[i].setText(labels[i]);
                fields[i] = panel.rowFields[i];
                fields[i].setText(initialValues != null ? initialValues[i] : "");
            }
        }

        int result = JOptionPane.showConfirmDialog(parent, panel, title,
                JOptionPane.OK_CANCEL_OPTION, JOptionPane.PLAIN_MESSAGE);
        if (result != JOptionPane.OK_OPTION) {
            return null;
        }

        String[] values = new String[labels.length];
        for (int i = 0; i < labels.length; i++) {
            values[i] = fields[i].getText().trim();
        }
        return values;
    }

