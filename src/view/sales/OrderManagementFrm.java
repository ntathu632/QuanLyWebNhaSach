    private void btnViewActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnViewActionPerformed
        int row = tblOrders.getSelectedRow();
        if (row < 0 || row >= currentOrders.size()) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn 1 đơn hàng!");
            return;
        }
        showOrderDetail(currentOrders.get(row));
    }//GEN-LAST:event_btnViewActionPerformed

    private void tblOrdersMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblOrdersMouseClicked
        if (evt.getClickCount() == 2) {
            int row = tblOrders.getSelectedRow();
            if (row >= 0 && row < currentOrders.size()) {
                showOrderDetail(currentOrders.get(row));
            }
        }
    }//GEN-LAST:event_tblOrdersMouseClicked

    private void btnUpdateStatusActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateStatusActionPerformed
        int row = tblOrders.getSelectedRow();
        if (row < 0 || row >= currentOrders.size()) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn 1 đơn hàng!");
            return;
        }
        Order selected = currentOrders.get(row);

        String newStatus = UpdateOrderStatusDialog.ask(this, selected.getOrderID(), selected.getStatus());
        if (newStatus == null || newStatus.equals(selected.getStatus())) {
            return;
        }
        if (new OrderDAO().updateOrderStatus(selected.getOrderID(), newStatus)) {
            if ("Cancelled".equals(newStatus)) {
                // Đơn đã thanh toán mới có Payment (Pending huỷ thẳng thì UPDATE
                // này không khớp dòng nào, vô hại) — đánh dấu hoàn tiền cho khớp
                // với Orders.status, cùng cách InvoiceHistoryFrm đang làm.
                new PaymentDAO().updatePaymentStatus(selected.getOrderID(), "Refunded");
            }
            JOptionPane.showMessageDialog(this, "Đã cập nhật trạng thái đơn hàng!");
            reload();
        } else {
            JOptionPane.showMessageDialog(this, "Cập nhật thất bại! Vui lòng thử lại.");
        }
    }//GEN-LAST:event_btnUpdateStatusActionPerformed

    private void reload() {
        allOrders.clear();
        allOrders.addAll(new OrderDAO().getOrdersWithoutInvoice());
        applyFilter();
    }

    private void applyFilter() {
        String selected = (String) cboStatusFilter.getSelectedItem();
        currentOrders.clear();
        for (Order o : allOrders) {
            if (ALL_STATUSES.equals(selected) || o.getStatus().equals(selected)) {
                currentOrders.add(o);
            }
        }
        DefaultTableModel model = (DefaultTableModel) tblOrders.getModel();
        model.setRowCount(0);
        for (Order o : currentOrders) {
            model.addRow(new Object[]{o.getOrderID(), o.getCustomer().getFullName(),
                DATE_FMT.format(o.getOrderDate()), String.format("%,.0f₫", o.getTotalAmount()), o.getStatus()});
        }
    }

    /** FR-SALE-02: xem chi tiết 1 đơn hàng online — thông tin khách hàng + danh sách sách đã đặt. */
    private void showOrderDetail(Order order) {
        Customer c = order.getCustomer();
        SalesOrderDetailDialog.show(this, "Chi tiết đơn hàng #" + order.getOrderID(), new String[][]{
            {"Khách hàng:", c.getFullName()},
            {"Điện thoại:", c.getPhone() == null ? "—" : c.getPhone()},
            {"Email:", c.getEmail() == null ? "—" : c.getEmail()},
            {"Địa chỉ giao hàng:", order.getShippingAddress() == null ? "—" : order.getShippingAddress()}
        }, "Sách đã đặt", new OrderDAO().getOrderDetails(order.getOrderID()), order.getTotalAmount());
    }

