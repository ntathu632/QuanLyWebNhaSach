    private void doSearch() {
        String keyword = txtKeyword.getText().trim();
        if (keyword.isEmpty()) {
            return;
        }
        found = new CustomerDAO().searchCustomer(keyword);
        DefaultListModel<String> model = new DefaultListModel<>();
        for (Customer c : found) {
            model.addElement(c.getFullName() + " - " + c.getPhone());
        }
        lstResults.setModel(model);
        if (found.length == 0) {
            JOptionPane.showMessageDialog(this, "Không tìm thấy khách hàng nào!");
        } else {
            lstResults.setSelectedIndex(0);
            lstResults.requestFocusInWindow();
        }
    }

    /** Nhận khách đang chọn trong danh sách; chưa có kết quả nào thì bỏ qua. */
    private void choose() {
        int index = lstResults.getSelectedIndex();
        if (index < 0 || index >= found.length) {
            return;
        }
        result = found[index];
        dispose();
    }

