    private void btnViewActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnViewActionPerformed
        int row = tblInvoices.getSelectedRow();
        if (row < 0 || row >= currentInvoices.size()) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn 1 hóa đơn!");
            return;
        }
        showInvoiceDetail(currentInvoices.get(row));
    }//GEN-LAST:event_btnViewActionPerformed

    private void tblInvoicesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblInvoicesMouseClicked
        if (evt.getClickCount() == 2) {
            int row = tblInvoices.getSelectedRow();
            if (row >= 0 && row < currentInvoices.size()) {
                showInvoiceDetail(currentInvoices.get(row));
            }
        }
    }//GEN-LAST:event_tblInvoicesMouseClicked

    private void btnCancelInvoiceActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCancelInvoiceActionPerformed
        int row = tblInvoices.getSelectedRow();
        if (row < 0 || row >= currentInvoices.size()) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn 1 hóa đơn!");
            return;
        }
        Invoice selected = currentInvoices.get(row);
        if ("Cancelled".equals(selected.getOrderStatus())) {
            JOptionPane.showMessageDialog(this, "Hóa đơn này đã bị hủy trước đó!");
            return;
        }
        int confirm = JOptionPane.showConfirmDialog(this,
                "Hủy hóa đơn #" + selected.getInvoiceID() + " của khách \"" + selected.getCustomerName()
                + "\"? Số sách trong hóa đơn sẽ được hoàn lại vào tồn kho.",
                "Xác nhận hủy hóa đơn", JOptionPane.YES_NO_OPTION);
        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }
        if (new OrderDAO().updateOrderStatus(selected.getOrderID(), "Cancelled")) {
            new PaymentDAO().updatePaymentStatus(selected.getOrderID(), "Refunded");
            JOptionPane.showMessageDialog(this, "Đã hủy hóa đơn và hoàn tồn kho!");
            reload();
        } else {
            JOptionPane.showMessageDialog(this, "Hủy hóa đơn thất bại! Vui lòng thử lại.");
        }
    }//GEN-LAST:event_btnCancelInvoiceActionPerformed

    private void reload() {
        allInvoices.clear();
        allInvoices.addAll(new InvoiceDAO().getInStoreInvoices());
        applyFilter();
    }

    private void applyFilter() {
        String selected = (String) cboStatusFilter.getSelectedItem();
        currentInvoices.clear();
        for (Invoice iv : allInvoices) {
            if (ALL_STATUSES.equals(selected) || iv.getOrderStatus().equals(selected)) {
                currentInvoices.add(iv);
            }
        }
        DefaultTableModel model = (DefaultTableModel) tblInvoices.getModel();
        model.setRowCount(0);
        for (Invoice iv : currentInvoices) {
            model.addRow(new Object[]{iv.getInvoiceID(), DATE_FMT.format(iv.getInvoiceDate()),
                iv.getCustomerName(), iv.getEmployeeName(),
                String.format("%,.0f₫", iv.getTotalAmount()), iv.getOrderStatus()});
        }
    }

    /** Xem chi tiết 1 hóa đơn — thông tin thanh toán + danh sách sách đã bán. */
    private void showInvoiceDetail(Invoice invoice) {
        SalesOrderDetailDialog.show(this, "Chi tiết hóa đơn #" + invoice.getInvoiceID(), new String[][]{
            {"Khách hàng:", invoice.getCustomerName()},
            {"Nhân viên lập:", invoice.getEmployeeName()},
            {"Phương thức thanh toán:", invoice.getPaymentMethod()},
            {"Trạng thái:", invoice.getOrderStatus()}
        }, "Sách đã bán", new OrderDAO().getOrderDetails(invoice.getOrderID()), invoice.getTotalAmount());
    }

