    private void cboCategoryActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cboCategoryActionPerformed
        if (updatingCategory) {
            return;
        }
        String selected = (String) cboCategory.getSelectedItem();
        foundBooks.clear();
        if (ALL_CATEGORIES.equals(selected)) {
            if (!txtKeyword.getText().trim().isEmpty()) {
                foundBooks.addAll(Arrays.asList(new BookDAO().searchBook(txtKeyword.getText().trim())));
            }
        } else {
            txtKeyword.setText("");
            for (Category c : categories) {
                if (c.getCategoryName().equals(selected)) {
                    foundBooks.addAll(Arrays.asList(new BookDAO().searchByCategory(c.getCategoryID())));
                    break;
                }
            }
        }
        renderCards();
    }//GEN-LAST:event_cboCategoryActionPerformed

    private void btnRemoveLineActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoveLineActionPerformed
        int row = tblCart.getSelectedRow();
        if (row >= 0 && row < cartItems.size()) {
            cartItems.remove(row);
            refreshCart();
        }
    }//GEN-LAST:event_btnRemoveLineActionPerformed

    private void btnSubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitActionPerformed
        if (cartItems.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Hóa đơn chưa có sách nào!");
            return;
        }
        Customer customer = selectedCustomer;
        if (customer == null) {
            customer = new CustomerDAO().getOrCreateWalkInCustomer();
        }
        String paymentMethod = (String) cboPaymentMethod.getSelectedItem();
        int[] outOrderId = new int[1];
        String error = new InvoiceDAO().createInStoreSale(customer.getCustomerID(), cartItems, paymentMethod,
                employee.getEmployeeID(), outOrderId);
        if (error == null) {
            showReceiptDialog(outOrderId[0], customer, employee.getFullName(), paymentMethod, cartItems);
            // Mở lại trang trống cho hóa đơn tiếp theo.
            SalesNav.go(this, employee, "instore");
        } else {
            JOptionPane.showMessageDialog(this, error);
        }
    }//GEN-LAST:event_btnSubmitActionPerformed

