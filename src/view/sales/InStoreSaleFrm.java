    private void doSearchByKeyword() {
        updatingCategory = true;
        cboCategory.setSelectedItem(ALL_CATEGORIES);
        updatingCategory = false;
        foundBooks.clear();
        foundBooks.addAll(Arrays.asList(new BookDAO().searchBook(txtKeyword.getText().trim())));
        renderCards();
    }

    private void renderCards() {
        InventoryDAO inventoryDAO = new InventoryDAO();
        pnlCards.removeAll();
        for (Book b : foundBooks) {
            int stock = inventoryDAO.getInventoryForBook(b.getBookID()).getStockQuantity();
            pnlCards.add(bookCard(b, stock, () -> addBookToCart(b, stock)));
        }
        pnlCards.revalidate();
        pnlCards.repaint();
    }

    private void addBookToCart(Book book, int stock) {
        String input = JOptionPane.showInputDialog(this,
                "Số lượng cho \"" + book.getTitle() + "\" (còn " + stock + "):", "1");
        if (input == null) {
            return;
        }
        int qty;
        try {
            qty = Integer.parseInt(input.trim());
            if (qty <= 0) {
                throw new NumberFormatException();
            }
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Số lượng không hợp lệ!");
            return;
        }
        cartItems.add(new OrderDetail(qty, book.getPrice(), book.getPrice() * qty, book));
        refreshCart();
    }

    private void refreshCart() {
        DefaultTableModel model = (DefaultTableModel) tblCart.getModel();
        model.setRowCount(0);
        float total = 0f;
        for (OrderDetail d : cartItems) {
            model.addRow(new Object[]{d.getBook().getTitle(), d.getQuantity(), String.format("%,.0f₫", d.getSubtotal())});
            total += d.getSubtotal();
        }
        lblTotal.setText("Tổng cộng: " + String.format("%,.0f₫", total));
    }

