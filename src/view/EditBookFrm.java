    private void populateFields() {
        lblBookID.setText(String.valueOf(book.getBookID()));
        txtISBN.setText(book.getISBN());
        txtTitle.setText(book.getTitle());
        txtPrice.setText(String.valueOf(book.getPrice()));
        txtDescription.setText(book.getDescription());
        txtImage.setText(book.getImage());
    }

    @Override
    public void actionPerformed(ActionEvent e) {
        if (e.getSource() == btnReset) {
            populateFields();
        } else if (e.getSource() == btnSave) {
            String isbn = txtISBN.getText().trim();
            String title = txtTitle.getText().trim();

            if (isbn.isEmpty() || title.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Vui lòng nhập đầy đủ ISBN và Tên sách!");
                return;
            }

            float price;
            try {
                price = Float.parseFloat(txtPrice.getText().trim());
            } catch (NumberFormatException ex) {
                JOptionPane.showMessageDialog(this, "Giá bán không hợp lệ!");
                return;
            }

            book.setISBN(isbn);
            book.setTitle(title);
            book.setPrice(price);
            book.setDescription(txtDescription.getText().trim());
            book.setImage(txtImage.getText().trim());

            BookDAO bookDAO = new BookDAO();
            if (bookDAO.updateBook(book)) {
                JOptionPane.showMessageDialog(this, "Cập nhật sách thành công!");
                (new ManageBooksFrm(account)).setVisible(true);
                this.dispose();
            } else {
                JOptionPane.showMessageDialog(this, "Cập nhật thất bại! Vui lòng thử lại.");
            }
        }
    }
