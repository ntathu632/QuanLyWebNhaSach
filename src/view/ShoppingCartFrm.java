    private void loadCartItems() {
        ShoppingCartDAO shoppingCartDAO = new ShoppingCartDAO();
        CartItem[] items = shoppingCartDAO.getCartItems(cart);
        cart.setItems(items);

        cartItemsFound.clear();
        DefaultTableModel model = (DefaultTableModel) tblCartItem.getModel();
        model.setRowCount(0);
        for (CartItem item : items) {
            cartItemsFound.add(item);
            model.addRow(new Object[]{
                item.getBook().getBookID(), item.getBook().getTitle(),
                item.getQuantity(), item.getUnitPrice(), item.getSubtotal()
            });
        }
    }

    @Override
    public void actionPerformed(ActionEvent e) {
        if (e.getSource() == btnRemove) {
            int row = tblCartItem.getSelectedRow();
            if (row < 0 || row >= cartItemsFound.size()) {
                JOptionPane.showMessageDialog(this, "Vui lòng chọn 1 sách trong giỏ hàng để xóa!");
                return;
            }

            ShoppingCartDAO shoppingCartDAO = new ShoppingCartDAO();
            if (shoppingCartDAO.removeCartItem(cartItemsFound.get(row))) {
                loadCartItems();
            } else {
                JOptionPane.showMessageDialog(this, "Xóa sách khỏi giỏ hàng thất bại!");
            }
        } else if (e.getSource() == btnCheckout) {
            if (cartItemsFound.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Giỏ hàng đang trống!");
                return;
            }

            OrderDetail[] details = new OrderDetail[cartItemsFound.size()];
            float total = 0;
            for (int i = 0; i < cartItemsFound.size(); i++) {
                CartItem item = cartItemsFound.get(i);
                details[i] = new OrderDetail(item.getQuantity(), item.getUnitPrice(), item.getSubtotal(), item.getBook());
                total += item.getSubtotal();
            }

            Order order = new Order();
            order.setOrderDate(new Date());
            order.setTotalAmount(total);
            order.setStatus("Pending");
            order.setCustomer(cart.getCustomer());
            order.setDetails(details);
            order.setCartID(cart.getCartID());

            (new CheckoutFrm(order)).setVisible(true);
            this.dispose();
        }
    }
