    /** statusLabel: trạng thái đã đổi sang chữ tiếng Việt (vd "Chờ xử lý"). */
    static void show(Component parent, Order order, String statusLabel) {
        OrderDetailDialog d = new OrderDetailDialog(AppTheme.windowOf(parent));
        d.setTitle("Chi tiết đơn hàng #" + order.getOrderID());
        d.lblInfo.setText("<html>Trạng thái: <b>" + statusLabel + "</b><br>"
                + "Địa chỉ giao hàng: " + (order.getShippingAddress() == null ? "" : order.getShippingAddress()) + "<br>"
                + "Tổng tiền: <b>" + String.format("%,.0f₫", order.getTotalAmount()) + "</b></html>");
        List<OrderDetail> details = new OrderDAO().getOrderDetails(order.getOrderID());
        DefaultTableModel model = (DefaultTableModel) d.tblItems.getModel();
        for (OrderDetail item : details) {
            model.addRow(new Object[]{item.getBook().getTitle(), item.getQuantity(),
                String.format("%,.0f₫", item.getUnitPrice()), String.format("%,.0f₫", item.getSubtotal())});
        }
        d.setVisible(true);
    }

