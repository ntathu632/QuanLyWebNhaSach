    // Thẻ thống kê thật (đơn hàng + chi tiêu), dùng chung dữ liệu OrderDAO với
    // "Đơn hàng của tôi" — thay cho khối "Loyalty Credit" trong mẫu (không có
    // hệ thống điểm thưởng thật nên không đưa số bịa vào).
    private void loadStats() {
        List<Order> orders = new OrderDAO().getOrdersByCustomer(customer.getCustomerID());
        float totalSpent = 0f;
        for (Order o : orders) {
            if ("Paid".equals(o.getStatus())) {
                totalSpent += o.getTotalAmount();
            }
        }
        lblStatOrdersValue.setText(String.valueOf(orders.size()));
        lblStatSpentValue.setText(String.format(java.util.Locale.forLanguageTag("vi-VN"), "%,.0f đ", totalSpent));
    }

    // Khối hồ sơ tóm tắt + giá trị các mục thông tin. Không có "Customer
