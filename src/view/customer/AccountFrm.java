    /** Lưu 1 mục thông tin đang sửa; thành công thì cập nhật lại khối hồ sơ và quay về thẻ "view". */
    private void saveField(JPanel row, String label, JTextField txt, BiConsumer<Customer, String> setter,
            boolean required, boolean isEmail) {
        String v = txt.getText().trim();
        if (required && v.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Trường \"" + label + "\" không được để trống!");
            return;
        }
        if (isEmail && !v.isEmpty() && !v.contains("@")) {
            JOptionPane.showMessageDialog(this, "Email không hợp lệ!");
            return;
        }
        // Giữ lại giá trị cũ: lưu CSDL thất bại thì trả đối tượng customer về như
        // trước, tránh giá trị chưa lưu nằm lại trong bộ nhớ (Shell dùng chung
        // đối tượng này) rồi bị gửi kèm ở lần lưu trường khác.
        String oldFullName = customer.getFullName();
        String oldPhone = customer.getPhone();
        String oldEmail = customer.getEmail();
        String oldAddress = customer.getAddress();
        setter.accept(customer, v);
        String error = new CustomerDAO().updateCustomer(customer);
        if (error == null) {
            loadProfile();
            shell.showLoginState();
            showCard(row, "view");
        } else {
            customer.setFullName(oldFullName);
            customer.setPhone(oldPhone);
            customer.setEmail(oldEmail);
            customer.setAddress(oldAddress);
            JOptionPane.showMessageDialog(this, error);
        }
    }

    private BufferedImage loadAvatarImage(String filename) {
        File file = AvatarStore.resolve(filename);
        if (file == null || !file.exists()) {
            return null;
        }
        try {
            return ImageIO.read(file);
        } catch (Exception ex) {
            return null;
        }
    }

    /** Bấm vào ảnh đại diện: chọn ảnh mới từ máy (JFileChooser) và lưu lại. */
    private void chooseAndUploadAvatar() {
        JFileChooser chooser = new JFileChooser();
        chooser.setDialogTitle("Chọn ảnh đại diện");
        chooser.setFileFilter(new FileNameExtensionFilter("Ảnh (jpg, jpeg, png, gif)", "jpg", "jpeg", "png", "gif"));
        if (chooser.showOpenDialog(this) != JFileChooser.APPROVE_OPTION) {
            return;
        }
        String filename = AvatarStore.save(chooser.getSelectedFile(), customer.getCustomerID());
        if (filename == null) {
            JOptionPane.showMessageDialog(this, "Không thể lưu ảnh, vui lòng thử lại!");
            return;
        }
        if (new CustomerDAO().updateAvatar(customer.getCustomerID(), filename)) {
            customer.setAvatar(filename);
            loadProfile();
        } else {
            JOptionPane.showMessageDialog(this, "Cập nhật ảnh đại diện thất bại, vui lòng thử lại!");
        }
    }

