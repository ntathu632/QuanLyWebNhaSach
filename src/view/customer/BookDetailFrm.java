    // FR-CUS-09 (Rate Book): chỉ hiện form này khi khách đủ điều kiện (xem loadReviews()).
    private void btnSubmitReviewActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSubmitReviewActionPerformed
        Review review = new Review();
        review.setBookID(book.getBookID());
        review.setCustomerID(customer.getCustomerID());
        review.setRating(Integer.parseInt((String) cboRating.getSelectedItem()));
        review.setComment(txtComment.getText().trim());

        String error = new ReviewDAO().addReview(review);
        if (error == null) {
            JOptionPane.showMessageDialog(this, "Cảm ơn bạn đã đánh giá!");
            txtComment.setText("");
            loadReviews();
        } else {
            JOptionPane.showMessageDialog(this, error);
        }
    }//GEN-LAST:event_btnSubmitReviewActionPerformed

    // FR-CUS-09 (Rate Book): danh sách đánh giá thật + form gửi đánh giá nếu
    // khách đủ điều kiện (AS-01: đã mua sách này và đơn đã "Paid") và chưa
    // từng đánh giá cuốn này; không đủ điều kiện thì hiện dòng ghi chú lý do.
    private void loadReviews() {
        ReviewDAO reviewDAO = new ReviewDAO();
        List<Review> reviews = reviewDAO.getReviewsForBook(book.getBookID());
        float avg = reviewDAO.averageRating(book.getBookID());
        lblRating.setText(starsHtml(avg, reviews.size()));
        lblReviewSummary.setText(starsHtml(avg, reviews.size()));

        pnlReviewList.removeAll();
        SimpleDateFormat fmt = new SimpleDateFormat("dd/MM/yyyy");
        for (Review r : reviews) {
            pnlReviewList.add(reviewRow(r, fmt));
            pnlReviewList.add(Box.createVerticalStrut(10));
        }
        pnlReviewList.setVisible(!reviews.isEmpty());

        boolean guest = customer == null;
        boolean purchased = !guest && reviewDAO.hasPurchased(customer.getCustomerID(), book.getBookID());
        boolean alreadyReviewed = !guest && reviewDAO.hasReviewed(customer.getCustomerID(), book.getBookID());
        String note = null;
        if (guest) {
            note = "Đăng nhập để đánh giá cuốn sách này.";
        } else if (alreadyReviewed) {
            note = "Bạn đã đánh giá cuốn sách này.";
        } else if (!purchased) {
            note = "Chỉ khách hàng đã mua và thanh toán thành công cuốn sách này mới có thể đánh giá.";
        }
        lblReviewNote.setText(note == null ? "" : note);
        lblReviewNote.setVisible(note != null);
        pnlReviewForm.setVisible(note == null);

        pnlPage.revalidate();
        pnlPage.repaint();
    }

    /** 5 ngôi sao (đầy/rỗng theo điểm trung bình đã làm tròn) + số liệu bằng chữ, dạng HTML cho 1 JLabel. */
    private static String starsHtml(float avg, int count) {
        int rounded = Math.round(avg);
        String text = count == 0 ? "Chưa có đánh giá" : String.format("%.1f/5 (%d đánh giá)", avg, count);
        return "<html>" + stars(rounded) + "&nbsp;&nbsp;<span style='color:#8A8374'>" + text + "</span></html>";
    }

    // Raleway không có ký tự ★/☆ (hiện ra ô vuông) nên riêng phần sao dùng
    // font logic "Dialog" — Java tự lấy từ font hệ thống có ký tự này.
    private static String stars(int filled) {
        return "<span style='font-family:Dialog'>"
                + "<span style='color:#E0A53E'>" + "★".repeat(filled) + "</span>"
                + "<span style='color:#D8D1C2'>" + "☆".repeat(5 - filled) + "</span></span>";
    }

    /** 1 dòng đánh giá: tên + sao + ngày, bên dưới là nội dung (nếu có). */
    private JPanel reviewRow(Review r, SimpleDateFormat fmt) {
        JPanel row = new JPanel();
        row.setLayout(new BoxLayout(row, BoxLayout.Y_AXIS));
        row.setOpaque(false);
        row.setAlignmentX(JComponent.LEFT_ALIGNMENT);

        JLabel header = new JLabel("<html><b>" + BookCard.escape(r.getCustomerName()) + "</b>&nbsp;&nbsp;"
                + stars(r.getRating())
                + "&nbsp;&nbsp;<span style='color:#8A8374'>· " + fmt.format(r.getReviewDate()) + "</span></html>");
        header.setAlignmentX(JComponent.LEFT_ALIGNMENT);
        row.add(header);

        if (r.getComment() != null && !r.getComment().isEmpty()) {
            row.add(Box.createVerticalStrut(4));
            JTextArea comment = new JTextArea(r.getComment());
            comment.setEditable(false);
            comment.setFocusable(false);
            comment.setLineWrap(true);
            comment.setWrapStyleWord(true);
            comment.setOpaque(false);
            comment.setForeground(AppTheme.TEXT);
            comment.setBackground(Color.WHITE);
            comment.setBorder(null);
            comment.setAlignmentX(JComponent.LEFT_ALIGNMENT);
            row.add(comment);
        }
        return row;
    }

