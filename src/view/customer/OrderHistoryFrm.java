    private void btnDetailActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDetailActionPerformed
        int row = tblOrders.getSelectedRow();
        if (row < 0 || row >= currentOrders.size()) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn 1 đơn hàng để xem chi tiết!");
            return;
        }
        showOrderDetail(currentOrders.get(row));
    }//GEN-LAST:event_btnDetailActionPerformed

    private void btnCancelOrderActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCancelOrderActionPerformed
        int row = tblOrders.getSelectedRow();
        if (row < 0 || row >= currentOrders.size()) {
            JOptionPane.showMessageDialog(this, "Vui lòng chọn 1 đơn hàng để hủy!");
            return;
        }
        Order selected = currentOrders.get(row);
        if (!"Pending".equals(selected.getStatus())) {
            JOptionPane.showMessageDialog(this, "Chỉ có thể hủy đơn đang ở trạng thái \"Chờ xử lý\"!");
            return;
        }
        int confirm = JOptionPane.showConfirmDialog(this,
                "Bạn có chắc muốn hủy đơn hàng #" + selected.getOrderID() + "?",
                "Xác nhận hủy đơn", JOptionPane.YES_NO_OPTION);
        if (confirm != JOptionPane.YES_OPTION) {
            return;
        }
        if (new OrderDAO().updateOrderStatus(selected.getOrderID(), "Cancelled")) {
            JOptionPane.showMessageDialog(this, "Đã hủy đơn hàng!");
            loadOrders();
        } else {
            JOptionPane.showMessageDialog(this, "Hủy đơn hàng thất bại! Vui lòng thử lại.");
        }
    }//GEN-LAST:event_btnCancelOrderActionPerformed

    /** Đọc lại các đơn của khách từ DB và đổ vào bảng. */
    private void loadOrders() {
        List<Order> orders = new OrderDAO().getOrdersByCustomer(customer.getCustomerID());
        currentOrders.clear();
        currentOrders.addAll(orders);
        DefaultTableModel model = (DefaultTableModel) tblOrders.getModel();
        model.setRowCount(0);
        for (Order o : orders) {
            model.addRow(new Object[]{o.getOrderID(), DATE_FMT.format(o.getOrderDate()),
                String.format("%,.0f₫", o.getTotalAmount()), statusLabel(o.getStatus())});
        }
    }

    /** Hộp thoại chi tiết 1 đơn: trạng thái, địa chỉ, tổng tiền + bảng các sách trong đơn. */
    private void showOrderDetail(Order order) {
        OrderDetailDialog.show(this, order, statusLabel(order.getStatus()));
    }

    private String statusLabel(String status) {
        return switch (status) {
            case "Pending" -> "Chờ xử lý";
            case "Paid" -> "Đã thanh toán";
            case "Cancelled" -> "Đã hủy";
            default -> status;
        };
    }

    private Color statusColor(String label) {
        if ("Đã thanh toán".equals(label)) {
            return AppTheme.PRIMARY_HOVER;
        }
        if ("Đã hủy".equals(label)) {
            return AppTheme.ACCENT_TEXT;
        }
        return AppTheme.CHART_ORANGE;
    }

