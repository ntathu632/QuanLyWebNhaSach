    private void completePayment() {
        Payment payment = new Payment();
        payment.setPaymentDate(new Date());
        payment.setAmount(order.getTotalAmount());
        payment.setPaymentMethod(gateway);
        payment.setStatus("Paid");
        payment.setOrderID(order.getOrderID());

        if (new PaymentDAO().addPayment(payment)) {
            new OrderDAO().updateOrderStatus(order.getOrderID(), "Paid");
            JOptionPane.showMessageDialog(this, gateway + " báo giao dịch thành công! Đơn hàng đã được thanh toán.");
            shell.navigateTo(new CustomerHomeFrm(customer));
        } else {
            JOptionPane.showMessageDialog(this, "Giao dịch thất bại! Vui lòng thử lại.");
            shell.navigateTo(new PaymentFrm(customer, order));
        }
    }

    /**
     * Mã QR minh họa — pattern tất định theo orderID (KHÔNG phải QR quét được
     * thật, chỉ để giao diện giống cổng thanh toán thật hơn là 1 nút bấm trơn).
     * Làm dạng Icon để gắn vào lblQr đặt sẵn trong Design.
     */
    private static class QrIcon implements Icon {

        private final int seed;
        private final int size;

        QrIcon(int seed, int size) {
            this.seed = seed;
            this.size = size;
        }

        @Override
        public int getIconWidth() {
            return size;
        }

        @Override
        public int getIconHeight() {
            return size;
        }

        @Override
        public void paintIcon(Component c, Graphics g, int x, int y) {
            Graphics2D g2 = (Graphics2D) g.create();
            g2.translate(x, y);
            g2.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON);
            g2.setColor(Color.WHITE);
            g2.fillRect(0, 0, size, size);
            g2.setColor(new Color(0xDD, 0xDD, 0xDD));
            g2.drawRect(0, 0, size - 1, size - 1);

            int cells = 16;
            int cellSize = size / cells;
            Random rnd = new Random(seed * 7919L);
            g2.setColor(new Color(0x22, 0x22, 0x22));
            for (int row = 0; row < cells; row++) {
                for (int col = 0; col < cells; col++) {
                    boolean isFinder = (col < 3 && row < 3) || (col >= cells - 3 && row < 3) || (col < 3 && row >= cells - 3);
                    if (isFinder || rnd.nextBoolean()) {
                        g2.fillRect(col * cellSize, row * cellSize, cellSize - 1, cellSize - 1);
                    }
                }
            }
            g2.dispose();
        }
    }

