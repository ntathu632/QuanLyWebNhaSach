    private void btnConfirmActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnConfirmActionPerformed
        String shippingAddress = txtShippingAddress.getText().trim();
        if (shippingAddress.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập địa chỉ giao hàng!");
            return;
        }

        order.setShippingAddress(shippingAddress);
        order.setPaymentMethod((String) cboPaymentMethod.getSelectedItem());

        String error = new OrderDAO().addOrder(order);
        if (error == null) {
            AppTheme.switchFrame(this, new PaymentFrm(customer, order));
        } else {
            JOptionPane.showMessageDialog(this, error);
        }
    }//GEN-LAST:event_btnConfirmActionPerformed

