    /** Tìm theo từ khóa đang gõ; nếu đang lọc theo danh mục mà chưa gõ gì thì hiện sách của danh mục đó. */
    private void doSearch() {
        String keyword = txtKeyword.getText().trim();
        Book[] found;
        if (categoryId != null && keyword.isEmpty()) {
            found = new BookDAO().searchByCategory(categoryId);
        } else {
            leaveCategoryMode();
            found = new BookDAO().searchBook(keyword);
        }
        pnlResults.removeAll();
        for (Book book : found) {
            pnlResults.add(BookCard.build(book, () -> AppTheme.switchFrame(this, new BookDetailFrm(customer, book))));
        }
        lblResultCount.setText("Tìm thấy " + found.length + " cuốn sách");
        pnlResults.revalidate();
        pnlResults.repaint();
        scrResults.getVerticalScrollBar().setValue(0);
    }

    private void leaveCategoryMode() {
        categoryId = null;
        lblCategoryBadge.setVisible(false);
    }

    /** Ô tìm kiếm trên navbar: đưa từ khóa xuống ô tìm kiếm của trang rồi tìm luôn. */
    private void searchFromNavbar() {
        txtKeyword.setText(txtSearch.getText().trim());
        leaveCategoryMode();
        doSearch();
    }

    private void login(boolean startWithRegister) {
        Customer c = CustomerLogin.show(this, startWithRegister);
        if (c != null) {
            customer = c;
            showLoginState();
        }
    }

    /** true nếu đã đăng nhập tài khoản Khách hàng; nếu chưa thì bật hộp thoại đăng nhập. */
    private boolean ensureLoggedIn() {
        if (customer == null) {
            login(false);
        }
        return customer != null && isDisplayable();
    }

    /** Ẩn/hiện cụm nút bên phải navbar theo trạng thái đăng nhập. */
    private void showLoginState() {
        boolean guest = customer == null;
        btnLogin.setVisible(guest);
        btnRegister.setVisible(guest);
        lblUser.setVisible(!guest);
        btnAccount.setVisible(!guest);
        btnChangePassword.setVisible(!guest);
        btnLogout.setVisible(!guest);

        if (guest) {
            lblCartBadge.setVisible(false);
        } else {
            String name = customer.getFullName() != null ? customer.getFullName() : "khách hàng";
            lblUser.setText("Xin chào, " + name);
            int count = new ShoppingCartDAO().countItemsIfCartExists(customer);
            lblCartBadge.setText(String.valueOf(count));
            lblCartBadge.setVisible(count > 0);
        }
        pnlNavRight.revalidate();
        pnlNavRight.repaint();
    }

