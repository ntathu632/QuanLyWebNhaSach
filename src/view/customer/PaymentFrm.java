    private void btnPayActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPayActionPerformed
        String method = order.getPaymentMethod();
        if ("VNPay".equals(method) || "Momo".equals(method)) {
            AppTheme.switchFrame(this, new MockPaymentGatewayFrm(customer, order, method));
            return;
        }

        Payment payment = new Payment();
        payment.setPaymentDate(new Date());
        payment.setAmount(order.getTotalAmount());
        payment.setPaymentMethod(order.getPaymentMethod());
        payment.setStatus("Paid");
        payment.setOrderID(order.getOrderID());

        if (new PaymentDAO().addPayment(payment)) {
            new OrderDAO().updateOrderStatus(order.getOrderID(), "Paid");
            JOptionPane.showMessageDialog(this, "Thanh toán và đặt hàng thành công!");
            AppTheme.switchFrame(this, new CustomerHomeFrm(customer));
        } else {
            JOptionPane.showMessageDialog(this, "Thanh toán thất bại! Vui lòng thử lại.");
        }
    }//GEN-LAST:event_btnPayActionPerformed

