    @Override
    public void actionPerformed(ActionEvent e) {
        if (e.getSource() == btnAddToCart) {
            int quantity;
            try {
                quantity = Integer.parseInt(txtQuantity.getText().trim());
                if (quantity <= 0) {
                    throw new NumberFormatException();
                }
            } catch (NumberFormatException ex) {
                JOptionPane.showMessageDialog(this, "Số lượng không hợp lệ!");
                return;
            }

            float unitPrice = book.getPrice();
            float subtotal = unitPrice * quantity;

            CartItem item = new CartItem(quantity, unitPrice, subtotal, book);

            ShoppingCartDAO shoppingCartDAO = new ShoppingCartDAO();
            ShoppingCart cart = shoppingCartDAO.getOrCreateCart(customer);
            item.setCartID(cart.getCartID());

            if (shoppingCartDAO.addCartItem(item)) {
                JOptionPane.showMessageDialog(this, "Đã thêm sách vào giỏ hàng!");
            } else {
                JOptionPane.showMessageDialog(this, "Thêm vào giỏ hàng thất bại! Vui lòng thử lại.");
            }
        } else if (e.getSource() == btnViewCart) {
            ShoppingCartDAO shoppingCartDAO = new ShoppingCartDAO();
            ShoppingCart cart = shoppingCartDAO.getOrCreateCart(customer);
            (new ShoppingCartFrm(cart)).setVisible(true);
            this.dispose();
        }
    }
